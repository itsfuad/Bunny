// DrawBitmapText renders text using bitmap font data
func DrawBitmapText(program uint32, text string, x, y, charWidth, charHeight float32, color [4]float32) {
	gl.UseProgram(program)
	colorUniform := gl.GetUniformLocation(program, gl.Str("color\x00"))
	gl.Uniform4fv(colorUniform, 1, &color[0])

	for i, char := range text {
		charX := x + float32(i)*charWidth
		drawBitmapChar(char, charX, y, charWidth, charHeight)
	}
}

func drawBitmapChar(char rune, x, y, w, h float32) {
	// Convert to uppercase for lookup
	if char >= 'a' && char <= 'z' {
		char = char - 32
	}

	bitmap, exists := fontData[char]
	if !exists {
		// Draw a small rectangle for unknown characters
		drawPixel(x+w*0.2, y+h*0.2, w*0.6, h*0.6)
		return
	}

	// Special handling for space character
	if char == ' ' {
		// Spaces are invisible - just return (takes up width but shows nothing)
		return
	}

	// Each byte represents a row, each bit represents a pixel
	pixelWidth := w / 8.0
	pixelHeight := h / 7.0

	for row := 0; row < 7; row++ {
		rowData := bitmap[row]
		for col := 0; col < 8; col++ {
			if (rowData>>(7-col))&1 == 1 {
				pixelX := x + float32(col)*pixelWidth
				pixelY := y + h - float32(row+1)*pixelHeight
				drawPixel(pixelX, pixelY, pixelWidth, pixelHeight)
			}
		}
	}
}

func drawPixel(x, y, w, h float32) {
	vertices := []float32{
		x, y,
		x + w, y,
		x + w, y + h,
		x, y + h,
	}

	var vao, vbo uint32
	gl.GenVertexArrays(1, &vao)
	gl.GenBuffers(1, &vbo)
	gl.BindVertexArray(vao)
	gl.BindBuffer(gl.ARRAY_BUFFER, vbo)
	gl.BufferData(gl.ARRAY_BUFFER, len(vertices)*4, gl.Ptr(vertices), gl.STATIC_DRAW)
	gl.VertexAttribPointer(0, 2, gl.FLOAT, false, 2*4, nil)
	gl.EnableVertexAttribArray(0)

	gl.DrawArrays(gl.TRIANGLE_FAN, 0, 4)

	gl.BindVertexArray(0)
	gl.DeleteVertexArrays(1, &vao)
	gl.DeleteBuffers(1, &vbo)
}
